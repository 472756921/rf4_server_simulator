// genwire —— 从 wire_spec.json 生成 internal/wiregen/tables.go（类型表+ops+字段注解）。
//
// 用法：go run ./tools/genwire -spec internal/wiregen/testdata/wire_spec.json -out internal/wiregen/tables.go
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"strings"
)

type spec struct {
	TypeToClass map[string]string    `json:"type_to_class"`
	Classes     map[string]specClass `json:"classes"`
	Stats       map[string]int       `json:"_stats"`
}

type specClass struct {
	TypeID *int        `json:"type_id"`
	Ops    []string    `json:"ops"`
	DTO    string      `json:"dto"`
	Fields []specField `json:"fields"`
}

type specField struct {
	Idx   int    `json:"idx"`
	Name  string `json:"name"`
	Label string `json:"label"`
	Enum  string `json:"enum"`
	Zh    string `json:"zh"`
}

func main() {
	specPath := flag.String("spec", "internal/wiregen/testdata/wire_spec.json", "wire_spec.json 路径")
	outPath := flag.String("out", "internal/wiregen/tables.go", "输出 Go 文件路径")
	flag.Parse()

	raw, err := os.ReadFile(*specPath)
	if err != nil {
		fmt.Fprintln(os.Stderr, "读取 spec:", err)
		os.Exit(1)
	}
	var s spec
	if err := json.Unmarshal(raw, &s); err != nil {
		fmt.Fprintln(os.Stderr, "解析 spec:", err)
		os.Exit(1)
	}

	var b strings.Builder
	b.WriteString("// Code generated by tools/genwire from wire_spec.json; DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// 数据源：协议类型规格（type_id registry + reader ops\n")
	b.WriteString("// 再 go generate ./internal/wiregen 或 go run ./tools/genwire。\n\n")
	b.WriteString("package wiregen\n\n")
	b.WriteString("import \"rf4server/internal/proto\"\n\n")

	// TypeToClass
	b.WriteString("// TypeToClass type_id -> wire 类名（含负数信封类 -1/-2）。\n")
	b.WriteString("var TypeToClass = map[int32]string{\n")
	for k, v := range s.TypeToClass {
		b.WriteString(fmt.Sprintf("\t%s: %s,\n", goInt(k), goStr(v)))
	}
	b.WriteString("}\n\n")

	// ClassOps + ClassTypeID
	b.WriteString("// ClassOps wire 类名 -> 位置化字段 op 序列（reader_ops2.json）。\n")
	b.WriteString("var ClassOps = map[string][]string{\n")
	for _, name := range sortedKeys(s.Classes) {
		c := s.Classes[name]
		if len(c.Ops) == 0 {
			continue
		}
		quoted := make([]string, 0, len(c.Ops))
		for _, op := range c.Ops {
			quoted = append(quoted, goStr(op))
		}
		b.WriteString(fmt.Sprintf("\t%s: {%s},\n", goStr(name), strings.Join(quoted, ", ")))
	}
	b.WriteString("}\n\n")

	b.WriteString("// ClassTypeID wire 类名 -> type_id（无则为 0，需查 TypeToClass 反查）。\n")
	b.WriteString("var ClassTypeID = map[string]int32{\n")
	for _, name := range sortedKeys(s.Classes) {
		c := s.Classes[name]
		if c.TypeID != nil {
			b.WriteString(fmt.Sprintf("\t%s: %d,\n", goStr(name), *c.TypeID))
		}
	}
	b.WriteString("}\n\n")

	// ClassMeta（字段注解）
	b.WriteString("// ClassMeta 字段注解（协议描述符，idx/name/label/enum/zh）。\n")
	b.WriteString("var ClassMeta = map[string]ClassInfo{\n")
	for _, name := range sortedKeys(s.Classes) {
		c := s.Classes[name]
		if len(c.Fields) == 0 && c.DTO == "" {
			continue
		}
		var fb strings.Builder
		for _, f := range c.Fields {
			fb.WriteString(fmt.Sprintf("\t\t{Idx: %d, Name: %s, Label: %s, Enum: %s, Zh: %s},\n",
				f.Idx, goStr(f.Name), goStr(f.Label), goStr(f.Enum), goStr(f.Zh)))
		}
		b.WriteString(fmt.Sprintf("\t%s: {DTO: %s, Fields: []FieldInfo{\n%s\t}},\n",
			goStr(name), goStr(c.DTO), fb.String()))
	}
	b.WriteString("}\n\n")

	// 便捷类型与方法
	b.WriteString(`// FieldInfo 一个 wire 字段的注解信息。
type FieldInfo struct {
	Idx   int
	Name  string
	Label string
	Enum  string
	Zh    string
}

// ClassInfo 类级元信息。
type ClassInfo struct {
	DTO    string
	Fields []FieldInfo
}

// Table 返回供 internal/proto 编解码使用的运行时 ops 表（进程内单例即可）。
func Table() *proto.OpsTable {
	return proto.NewOpsTable(TypeToClass, ClassOps)
}

// ClassForType type_id -> wire 类名。
func ClassForType(tid int32) string { return TypeToClass[tid] }

// OpsFor 类名 -> ops 序列。
func OpsFor(class string) []string { return ClassOps[class] }
`)

	if err := os.WriteFile(*outPath, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "写生成文件:", err)
		os.Exit(1)
	}
	fmt.Printf("genwire: %d classes, %d type_ids -> %s\n", len(s.Classes), len(s.TypeToClass), *outPath)
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	for i := 1; i < len(keys); i++ {
		for j := i; j > 0 && keys[j] < keys[j-1]; j-- {
			keys[j], keys[j-1] = keys[j-1], keys[j]
		}
	}
	return keys
}

func goStr(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func goInt(s string) string {
	return s // JSON 里键本身是十进制整数字符串（含负号）
}
